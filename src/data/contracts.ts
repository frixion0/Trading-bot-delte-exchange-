export function createCustomContract(symbolInput: string, basePrice: number = 10.0): CryptoContract {
  const cleanSymbol = symbolInput.trim().toUpperCase().replace(/[^A-Z0-9]/g, '');
  const quoteAsset = cleanSymbol.endsWith('USDT') ? 'USDT' : 'USD';
  const baseAsset = cleanSymbol.replace(quoteAsset, '') || cleanSymbol;
  
  let multiplier = 1;
  if (basePrice > 10000) multiplier = 0.001;
  else if (basePrice > 1000) multiplier = 0.01;
  else if (basePrice > 100) multiplier = 0.1;
  else if (basePrice < 0.01) multiplier = 10000;
  else if (basePrice < 1) multiplier = 100;

  return {
    symbol: cleanSymbol,
    name: `${baseAsset} Perpetual Futures`,
    category: 'Custom',
    baseAsset,
    quoteAsset,
    markPrice: basePrice,
    lastPrice: basePrice,
    high24h: +(basePrice * 1.05).toFixed(4),
    low24h: +(basePrice * 0.95).toFixed(4),
    change24h: 1.5,
    volume24h: 50000000,
    contractMultiplier: multiplier,
    tickSize: basePrice < 1 ? 0.0001 : 0.01,
    minLots: 1,
    maxLots: 100000,
    maxLeverage: 50,
    fundingRate: 0.01,
  };
}
